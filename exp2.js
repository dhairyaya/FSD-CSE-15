let add=(a,b)=>a+b; //arrow function is a shorter syntax for writing functions in JavaScript. It allows you to write functions in a more concise way, especially for simple operations like addition. In this case, the arrow function takes two parameters, `a` and `b`, and returns their sum.
console.log("sum=",add());
console.log("sum=",add(1));
console.log("sum=",add(11,3));